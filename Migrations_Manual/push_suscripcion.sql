-- Suscripciones Web Push (avisos al celular). Aplicar en pgAdmin.
CREATE TABLE IF NOT EXISTS push_suscripcion (
    push_suscripcion_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             integer NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    endpoint            text    NOT NULL,
    p256dh              text    NOT NULL,
    auth                text    NOT NULL,
    user_agent          text    NULL,
    created_date_time   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_push_suscripcion_endpoint ON push_suscripcion (endpoint);
CREATE INDEX IF NOT EXISTS ix_push_suscripcion_user_id ON push_suscripcion (user_id);
